/**
 * workspace-docs store.
 *
 * The canonical store is one SQLite database at
 * `<workspace>/.pi/workspace-docs/store.sqlite`, opened through the built-in
 * `node:sqlite` module. A mutation is one transaction; a stale revision is
 * rejected with no write. The store never resets or rewrites an unreadable
 * database.
 *
 * Each document row keeps its metadata and its canonical body. Checkout renders
 * fresh front matter over that body, so an unchanged round-trip compares equal.
 */
